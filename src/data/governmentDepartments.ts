export function getDepartmentByAbbreviation(abbreviation: string): GovernmentDepartment | undefined {
  return GOVERNMENT_DEPARTMENTS.find(
    (d) => d.abbreviation.toLowerCase() === abbreviation.toLowerCase()
  );
}

export function getDepartmentsByCity(cityName: string): GovernmentDepartment[] {
  return GOVERNMENT_DEPARTMENTS.filter(
    (d) => d.cities.some((c) => c.toLowerCase() === cityName.toLowerCase())
  );
}

export function getDepartmentsByCategory(category: IssueCategory): GovernmentDepartment[] {
  return GOVERNMENT_DEPARTMENTS.filter((d) => d.category === category);
}

export function lookupDepartmentHelpline(departmentName: string): string | null {
  const nameLower = departmentName.toLowerCase();
  const match = GOVERNMENT_DEPARTMENTS.find(
    (d) =>
      nameLower.includes(d.abbreviation.toLowerCase()) ||
      nameLower.includes(d.fullName.toLowerCase())
  );
  return match?.helplines[0] ?? null;
}
